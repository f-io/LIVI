pub fn decode(charset: u8, bytes: &[u8]) -> String {
    let bytes = match bytes.iter().position(|&b| b == 0) {
        Some(end) => &bytes[..end],
        None => bytes,
    };
    let text = match charset {
        15 => String::from_utf8_lossy(bytes).into_owned(),
        6 => {
            let units: Vec<u16> = bytes
                .as_chunks::<2>()
                .0
                .iter()
                .map(|c| u16::from_be_bytes(*c))
                .collect();
            String::from_utf16_lossy(&units)
        }
        4 => bytes.iter().map(|&b| b as char).collect(),
        _ => bytes
            .iter()
            .filter_map(|&b| char::from_u32(EBU_LATIN[b as usize] as u32))
            .filter(|c| !c.is_control())
            .collect(),
    };
    text.trim_end().to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ebu_latin_umlauts() {
        assert_eq!(
            decode(
                0,
                &[0x53, 0x57, 0x52, 0x33, 0x20, 0x91, 0x97, 0x99, 0x8d, 0x20]
            ),
            "SWR3 äöüß"
        );
        assert_eq!(decode(0, &[0xd1, 0xd7, 0xd9]), "ÄÖÜ");
    }

    #[test]
    fn utf8_and_padding() {
        assert_eq!(decode(15, "Köln  ".as_bytes()), "Köln");
        assert_eq!(decode(0, b"AB\0junk"), "AB");
    }
}
